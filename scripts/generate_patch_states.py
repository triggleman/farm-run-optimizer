#!/usr/bin/env python3
"""
Generates src/main/resources/com/herbrunhelper/patch-states.tsv from RuneLite's
Time Tracking plugin source (PatchImplementation.java and Produce.java).

Usage:
  python3 scripts/generate_patch_states.py <path to runelite/.../timetracking/farming>

RuneLite is BSD 2-Clause licensed; PatchImplementation.java is Copyright (c) 2019 Abex.
"""
import re
import sys
from pathlib import Path

TYPES = ["HERB", "ALLOTMENT", "FLOWER", "TREE", "FRUIT_TREE", "HARDWOOD_TREE", "BUSH", "HOPS", "CACTUS", "CALQUAT",
         "SPIRIT_TREE", "CELASTRUS", "REDWOOD"]


def produce_stages(text):
    stages = {}
    for m in re.finditer(r"^\s+([A-Z_]+)\((.*)\),?\s*$", text, re.M):
        args = [a.strip() for a in m.group(2).split(",")]
        nums = [a for a in args if re.fullmatch(r"\d+", a)]
        if "PatchImplementation." in m.group(2) and len(nums) >= 2:
            # (contract varbit?), tickrate, stages, [regrow, harvestStages]
            idx = [i for i, a in enumerate(args) if a.startswith("ItemID.")]
            if idx:
                after = args[idx[0] + 1:]
                stages[m.group(1)] = int(after[1])
    return stages


def evaluate(expr, value, stages):
    expr = re.sub(r"Produce\.([A-Z_]+)\.getStages\(\)", lambda m: str(stages[m.group(1)]), expr)
    return int(eval(expr.replace("value", str(value)), {"__builtins__": {}}))


def main(folder):
    folder = Path(folder)
    impl = (folder / "PatchImplementation.java").read_text()
    stages = produce_stages((folder / "Produce.java").read_text())
    rows = []
    for t in TYPES:
        m = re.search(r"^\t" + t + r"\(", impl, re.M)
        if not m:
            sys.exit("type not found: " + t)
        nxt = re.search(r"^\t[A-Z_]+\(", impl[m.end():], re.M)
        block = impl[m.start():m.end() + (nxt.start() if nxt else len(impl))]
        pat = re.compile(
            r"if \(value (?:>= (\d+) && value <= (\d+)|== (\d+))\)\s*\{\s*//\s*([^\n]*)\n\s*return new PatchState\(Produce\.(\w+), CropState\.(\w+), ([^;]+)\);",
            re.S)
        for g in pat.finditer(block):
            lo = int(g.group(1) or g.group(3))
            hi = int(g.group(2) or g.group(3))
            comment, crop, state, expr = g.group(4), g.group(5), g.group(6), g.group(7).strip()
            s0 = evaluate(expr, lo, stages)
            step = evaluate(expr, lo + 1, stages) - s0 if hi > lo else 0
            c = comment.lower()
            flag = "stump" if "stump" in c else "chop" if "chop down" in c else "check" if "check-health" in c else "-"
            rows.append((t, lo, hi, crop, state, s0, step, flag))
    out = Path(__file__).resolve().parent.parent / "src/main/resources/com/herbrunhelper/patch-states.tsv"
    with open(out, "w") as f:
        f.write("# Farming patch states: what each value of a patch's varbit means, per patch type.\n")
        f.write("#\n# Generated by scripts/generate_patch_states.py from RuneLite's Time Tracking plugin\n")
        f.write("# (PatchImplementation.java, Copyright (c) 2019 Abex), BSD 2-Clause License. See NOTICE.\n")
        f.write("#\n# Values lo..hi hold one crop and state; the stage at value v is stage + step * (v - lo).\n")
        f.write("# flag: check = ready for check-health, chop = grown tree to chop down, stump = tree stump.\n#\n")
        f.write("# type\tlo\thi\tcrop\tstate\tstage\tstep\tflag\n")
        for r in rows:
            f.write("\t".join(map(str, r)) + "\n")
    print(len(rows), "rows ->", out)


if __name__ == "__main__":
    main(sys.argv[1])
